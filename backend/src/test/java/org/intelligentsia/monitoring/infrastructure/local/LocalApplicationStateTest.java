package org.intelligentsia.monitoring.infrastructure.local;
import com.fasterxml.jackson.databind.*;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import java.nio.file.*;
import java.util.UUID;
import static org.junit.jupiter.api.Assertions.*;

class LocalApplicationStateTest {
    @TempDir Path directory;
    private JdbcTemplate memory() {
        var ds=new DriverManagerDataSource("jdbc:h2:mem:"+UUID.randomUUID()+";MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1","sa","");
        var jdbc=new JdbcTemplate(ds);
        for (String table:LocalApplicationState.TABLES) jdbc.execute("CREATE TABLE "+table+" (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, label VARCHAR(100))");
        jdbc.execute("CREATE TABLE atms (id BIGINT)"); jdbc.update("INSERT INTO atms VALUES (999)");
        return jdbc;
    }
    @Test void configurationSurvivesFreshMemoryAndNeverCopiesBusinessOrSessions() throws Exception {
        Path file=directory.resolve("state.json");
        Files.writeString(file,"{\"roles\":[{\"id\":12,\"label\":\"Opérateur\"}]}");
        JdbcTemplate first=memory();var writer=new LocalApplicationState(first,file.toString());writer.load();
        first.update("UPDATE roles SET label='Superviseur' WHERE id=12");
        first.update("INSERT INTO roles(label) VALUES ('Lecture seule')");writer.save();
        JsonNode saved=new ObjectMapper().readTree(file.toFile());
        assertFalse(saved.has("atms"));assertFalse(saved.has("monitoring_alerts"));assertFalse(saved.has("refresh_tokens"));
        JdbcTemplate next=memory();var reader=new LocalApplicationState(next,file.toString());reader.load();
        assertEquals("Superviseur",next.queryForObject("SELECT label FROM roles WHERE id=12",String.class));
        assertEquals(2,next.queryForObject("SELECT COUNT(*) FROM roles",Integer.class));
        assertTrue(next.queryForObject("SELECT MAX(id) FROM roles",Long.class)>12);
    }
    @Test void missingConfigurationFailsExplicitlyInsteadOfInventingRoles() {
        var store=new LocalApplicationState(memory(),directory.resolve("absent.json").toString());
        assertThrows(IllegalStateException.class,store::load);
    }
}
